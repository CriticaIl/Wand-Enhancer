// Embeds the (small, synthetic) sample saves into src/ui/sample-data.js so the
// single-file build can offer "Try a sample" without network access.
import { readFileSync, writeFileSync } from 'node:fs';

const list = [
  ['renpy8-1-1-LT1.save', "Ren'Py 8 save"],
  ['renpy-persistent-unsigned', "Ren'Py persistent"],
  ['rpgmaker-mv-file1.rpgsave', 'RPG Maker MV'],
  ['rpgmaker-mz-file1.rmmzsave', 'RPG Maker MZ'],
  ['sugarcube-the-lantern-road.save', 'SugarCube'],
  ['sandbox-base64.txt', 'HTML5 sandbox (Base64)'],
  ['gamemaker-save.ini', 'GameMaker INI'],
  ['storage-dump-example.json', 'Storage Bridge export'],
];
const items = list.map(([name, label]) => ({ name, label, data: readFileSync(new URL(`../samples/${name}`, import.meta.url)).toString('base64') }));
writeFileSync(
  new URL('../src/ui/sample-data.js', import.meta.url),
  `// Generated by tools/embed-samples.mjs — synthetic sample saves (base64).\nexport const SAMPLES = ${JSON.stringify(items, null, 1)};\n`,
);
console.log('embedded', items.length, 'samples');
